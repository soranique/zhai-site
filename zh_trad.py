"""简体转繁体（网站中文统一为繁体）。需要：pip install opencc-python-reimplemented

T(s) 用 OpenCC s2t，再按下面两张表修正神名、术语里容易转错的字。史料原文不经过这里：
哪些栏目不转，见 apply_traditional.py。
"""
import re

from opencc import OpenCC

_cc = OpenCC('s2t')
# 转换前保护：这些词按右边的写法输出
KEEP = {'斗母': '斗母', '南斗': '南斗', '北斗': '北斗', '东斗': '東斗', '西斗': '西斗', '中斗': '中斗', '太斗': '太斗', '星斗': '星斗',
        '四斗': '四斗', '魁斗': '魁斗', '鬼谷': '鬼谷', '溪谷': '溪谷', '暘谷': '暘谷', '蒿里': '蒿里', '万里': '萬里', '三尸': '三尸',
        '后土': '后土', '元后': '元后', '天后': '天后', '皇后': '皇后', '太后': '太后', '准提': '准提', '岳元帅': '岳元帥',
        '岳元帥': '岳元帥', '岳武穆': '岳武穆', '岳飞': '岳飛', '周公': '周公', '周言': '周言', '周作人': '周作人', '张三丰': '張三豐'}
# 转换后修正
FIX = [('鬥', '斗'), ('鹹', '咸'), ('捲', '卷'), ('菸', '煙'), ('羣', '群'), ('牀', '床'), ('瞭', '了'), ('纔', '才'), ('誌', '志'),
       ('雜志', '雜誌'), ('叢志', '叢誌'), ('標志', '標誌'),
       ('齋歷', '齋曆'), ('環形歷', '環形曆'), ('神誕歷', '神誕曆'), ('吉辰歷', '吉辰曆'), ('歷日', '曆日'), ('歷盤', '曆盤'), ('歷書', '曆書'),
       ('歷法', '曆法'), ('農歷', '農曆'), ('日歷', '日曆'), ('曆史', '歷史'), ('玉曆', '玉歷'), ('臺灣', '台灣'), ('首裏', '首里'),
       ('白嶽', '白岳'), ('諦閒', '諦閑'), ('文雲', '文云'), ('雲奉', '云奉'), ('週公', '周公'), ('餘治', '余治'), ('餘懷', '余懷'), ('几乎', '幾乎')]
_keys = list(KEEP)
_re = re.compile('|'.join(sorted(map(re.escape, _keys), key=len, reverse=True)))
_re2 = re.compile('(\\d+)')


def T(s):
    if not isinstance(s, str) or not re.search(r'[一-鿿]', s):
        return s
    t = _cc.convert(_re.sub(lambda m: '%d' % _keys.index(m.group()), s))
    t = _re2.sub(lambda m: KEEP[_keys[int(m.group(1))]], t)
    for a, b in FIX:
        t = t.replace(a, b)
    return t
